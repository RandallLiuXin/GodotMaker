REQUIRED_FINDING_FIELDS = (
    "rule_id",
    "group",
    "source",
    "rule_text",
    "requirement",
    "verdict",
    "evidence",
    "confidence",
    "disposition",
    "severity",
    "captures",
)


def validate_result(result: dict) -> list[str]:
    """Return a list of issues. Empty list = the graded result is schema-valid.

    Mirrors what `/gm-evaluate` writes into
    `visual_checks.<scene>.design_rules` and what gm-fixgap reads back.
    """
    issues: list[str] = []
    if result.get("schema") != design_rules.RESULT_SCHEMA:
        issues.append(f"schema must be {design_rules.RESULT_SCHEMA!r}")
    if result.get("result") not in {"pass", "fail", "warning"}:
        issues.append(f"result must be pass/fail/warning, got {result.get('result')!r}")
    if not isinstance(result.get("captures"), list) or not result["captures"]:
        issues.append("captures must be a non-empty list")
    for key in ("critical_issues", "major_issues", "minor_issues", "observational_na"):
        if not isinstance(result.get(key), list):
            issues.append(f"{key} must be a list (may be empty)")

    if result.get("backend_error"):
        if result.get("result") != "fail" or not result.get("critical_issues"):
            issues.append("a backend error must reject with a critical issue")
        return issues

    for index, finding in enumerate(result.get("findings", [])):
        for field in REQUIRED_FINDING_FIELDS:
            if field not in finding:
                issues.append(f"findings[{index}] missing {field!r}")
        if finding.get("verdict") not in design_rules.VERDICTS:
            issues.append(f"findings[{index}] bad verdict {finding.get('verdict')!r}")
        if finding.get("disposition") not in design_rules.DISPOSITIONS:
            issues.append(f"findings[{index}] bad disposition")
        if finding.get("severity") not in design_rules.SEVERITIES:
            issues.append(f"findings[{index}] bad severity")
        if finding.get("verdict") in ("fail", "uncertain") and not finding.get("evidence"):
            issues.append(f"findings[{index}] needs observable evidence")
        if finding.get("verdict") == "not_applicable":
            if finding.get("confidence") is not None:
                issues.append(f"findings[{index}] N/A carries a confidence")
            if not finding.get("na_reason"):
                issues.append(f"findings[{index}] N/A needs a reason")
        elif finding.get("confidence") not in design_rules.CONFIDENCES:
            issues.append(f"findings[{index}] bad confidence")
        if not finding.get("captures"):
            issues.append(f"findings[{index}] needs at least one capture")
    return issues


