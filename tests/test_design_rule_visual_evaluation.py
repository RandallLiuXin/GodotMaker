    findings = _all_pass(scene_request)
    for finding in findings:
        if finding["rule_id"] == "d6.r1":
            finding.update(verdict="not_applicable", evidence="")

    with pytest.raises(DesignError, match="requires a na_reason"):
        grade(scene_request, findings)

