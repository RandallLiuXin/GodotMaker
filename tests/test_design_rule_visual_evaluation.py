def _ids(rules: list[dict]) -> list[str]:
    return [rule["rule_id"] for rule in rules]


def _by_id(rules: list[dict]) -> dict[str, dict]:
    return {rule["rule_id"]: rule for rule in rules}


def _all_pass(request: dict, **overrides) -> list[dict]:
    """Findings where every applicable rule passes at high confidence."""
    findings = []
    for rule in request["rules"]:
        if not rule["applicable"]:
            findings.append({"rule_id": rule["rule_id"], "verdict": "not_applicable"})
            continue
        findings.append(
            {
                "rule_id": rule["rule_id"],
                "verdict": "pass",
                "evidence": f"observed: {rule['text'][:40]}",
                "confidence": "high",
            }
        )
    for rule_id, patch in overrides.items():
        for finding in findings:
            if finding["rule_id"] == rule_id.replace("__", "."):
                finding.update(patch)
                break
        else:  # pragma: no cover - guards fixture typos
            raise AssertionError(f"no finding for {rule_id}")
    return findings


def _single_fault(request: dict, rule_id: str, **patch) -> dict:
    """Grade a capture whose only deviation is `rule_id`."""
    findings = _all_pass(request)
    for finding in findings:
        if finding["rule_id"] == rule_id:
            finding.update(patch)
            break
    else:  # pragma: no cover - guards fixture typos
        raise AssertionError(f"no finding for {rule_id}")
    return grade(request, findings)


def _finding(result: dict, rule_id: str) -> dict:
    for finding in result["findings"]:
        if finding["rule_id"] == rule_id:
            return finding
    raise AssertionError(f"{rule_id} missing from graded findings")


